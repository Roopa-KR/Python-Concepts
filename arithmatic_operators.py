# arithmatic operators in python
# arithmatic operators are used to perform mathematical operations on numbers
# addition
a = 10
b = 5
print(a + b)  # Output: 15
# subtraction
print(a - b)  # Output: 5
# multiplication
print(a * b)  # Output: 50
# division
print(a / b)  # Output: 2.0
# floor division
print(a // b)  # Output: 2
# modulus
print(a % b)  # Output: 0
# exponentiation
print(a ** b)  # Output: 100000
