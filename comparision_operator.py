#Comparison operators in python
#Comparison operators are used to compare two values
#Equal
a = 10
b = 5
print(a == b)  # Output: False
#Not equal
print(a != b)  # Output: True
#Greater than
print(a > b)  # Output: True
#Less than
print(a < b)  # Output: False
#Greater than or equal to
print(a >= b)  # Output: True
#Less than or equal to
print(a <= b)  # Output: False