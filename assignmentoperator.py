#Assignment operator is used to assign a value to a variable. It is represented by the symbol "=". The assignment operator can be used in various ways, such as:

# Simple assignment
x = 10
print(x)  # Output: 10
# Augmented assignment
x += 5  # Equivalent to x = x + 5
print(x)  # Output: 15
x *= 2  # Equivalent to x = x * 2
print(x)  # Output: 30
x /= 3  # Equivalent to x = x / 3
print(x)  # Output: 10.0
x -= 2  # Equivalent to x = x - 2
print(x)  # Output: 8.0 
x //= 2  # Equivalent to x = x // 2
print(x)  # Output: 4.0 